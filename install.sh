#!/bin/sh
# shellcheck shell=bash
# Candidate loader variables intentionally remain confined to their installation subshell.
# shellcheck disable=SC2031
# Alpine may start this file with ash. Install the actual runtime dependencies, then re-exec Bash.
if [ -z "${BASH_VERSION:-}" ]; then
  if command -v apk >/dev/null 2>&1; then
    apk add --no-cache bash curl ca-certificates gzip tar coreutils findutils grep sed gawk || exit 1
  fi
  command -v bash >/dev/null 2>&1 || { echo '请先安装 bash。' >&2; exit 1; }
  exec bash "$0" "$@"
fi

set -eEuo pipefail
umask 077

REPO_OWNER="famintt"
REPO_NAME="Mihomo-Manager"
PROJECT_VERSION="v1.3.0"
PACKAGE_NAME="mihomo-manager-v1.3.0.tar.gz"
# Generated by scripts/build-release-bundle.sh --refresh; the bootstrap is outside the bundle.
PACKAGE_SHA256="e885d38c18adbbc471122ed4192ae2749586b92a945692b79edd07a332e321a5"
PACKAGE_URL="https://github.com/${REPO_OWNER}/${REPO_NAME}/releases/download/${PROJECT_VERSION}/${PACKAGE_NAME}"
INSTALL_BIN="/usr/local/bin/mm"
MTP_BIN="/usr/local/bin/mtp"

fail() { printf '安装包校验失败：%s\n' "$*" >&2; return 1; }
has_cmd() { command -v "$1" >/dev/null 2>&1; }

require_tools() {
  local cmd tar_version
  [ "${BASH_VERSINFO[0]}" -ge 4 ] || { fail '需要 bash 4 或以上版本'; return 1; }
  for cmd in bash gzip tar find sort awk grep mktemp chmod rm cmp stat sha256sum; do
    has_cmd "${cmd}" || { fail "缺少必需命令：${cmd}"; return 1; }
  done
  # Read the complete producer output: grep -q can close early and make GNU tar
  # fail with SIGPIPE under pipefail (observed on Alpine).
  tar_version="$(tar --version 2>/dev/null)" && [[ "${tar_version}" == *'GNU tar'* ]] || { fail '需要 GNU tar（Alpine: apk add tar）'; return 1; }
}

sha256_file() {
  local line
  line="$(sha256sum "$1")" || return 1
  printf '%s\n' "${line%% *}"
}

# MM_MODULES is parsed as data. Never source unverified candidate code to discover its inventory.
expected_files() {
  local root="$1" declaration module
  local -a module_names
  local -A seen=()
  declaration="$(grep '^MM_MODULES=' "${root}/lib/env.sh")" || return 1
  [[ "${declaration}" =~ ^MM_MODULES=\([a-z0-9\ -]+\)$ ]] || { fail 'MM_MODULES 声明无效或重复'; return 1; }
  declaration="${declaration#*=}"
  declaration="${declaration:1:-1}"
  read -r -a module_names <<<"${declaration}"
  [ "${module_names[0]:-}" = env ] || { fail 'MM_MODULES 首项必须为 env'; return 1; }
  for module in "${module_names[@]}"; do
    [[ "${module}" =~ ^[a-z][a-z0-9-]*$ ]] || return 1
    [ -z "${seen[${module}]:-}" ] || { fail "重复模块：${module}"; return 1; }
    seen["${module}"]=1
  done
  printf '%s\n' VERSION README.md mm.sh mtp.sh metadata/upstream.env scripts/watchdog.sh
  printf 'lib/%s.sh\n' "${module_names[@]}"
}

check_mode() {
  local actual
  actual="$(stat -c '%a' "$1")" || return 1
  [ "${actual}" = "$2" ] || { fail "权限 $1 为 ${actual}，应为 $2"; return 1; }
}

# This function also serves the local builder. It only reads candidate files.
validate_candidate() (
  local root="$1" tag="$2" expected actual directories special hardlinks path digest manifest='' version declaration
  [[ "${tag}" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || { fail '无效发布 tag'; return 1; }
  if [ ! -d "${root}" ] || [ -L "${root}" ]; then fail '候选根目录无效'; return 1; fi
  expected="$(expected_files "${root}" | LC_ALL=C sort)" || return 1
  actual="$(cd "${root}" && find . -type f -printf '%P\n' | LC_ALL=C sort)" || return 1
  [ "${actual}" = "$(printf '%s\nMANIFEST.sha256\n' "${expected}" | LC_ALL=C sort)" ] || { fail '文件清单不完整或包含额外文件'; return 1; }
  special="$(find "${root}" ! -type f ! -type d -print)" || return 1
  hardlinks="$(find "${root}" -type f -links +1 -print)" || return 1
  if [ -n "${special}" ] || [ -n "${hardlinks}" ]; then
    fail '候选含链接、硬链接或特殊文件'; return 1
  fi
  directories="$(cd "${root}" && find . -mindepth 1 -type d -printf '%P\n' | LC_ALL=C sort)" || return 1
  [ "${directories}" = $'lib\nmetadata\nscripts' ] || { fail '目录清单无效'; return 1; }
  for path in "${root}" "${root}/lib" "${root}/metadata" "${root}/scripts"; do check_mode "${path}" 755 || return 1; done
  check_mode "${root}/MANIFEST.sha256" 644 || return 1
  cmp -s <(printf '%s\n' "${tag}") "${root}/VERSION" || { fail 'VERSION 与发布 tag 不同'; return 1; }
  version="${tag#v}"
  for path in mm.sh mtp.sh; do
    declaration="$(grep '^SCRIPT_VERSION=' "${root}/${path}")" || return 1
    [ "${declaration}" = "SCRIPT_VERSION=\"${version}\"" ] || { fail "${path} 版本不一致"; return 1; }
  done
  declaration="$(grep '^REPO_OWNER=' "${root}/metadata/upstream.env")" || return 1
  [ "${declaration}" = 'REPO_OWNER="famintt"' ] || { fail '下载源 owner 不一致'; return 1; }
  while IFS= read -r path; do
    case "${path}" in
      mm.sh|mtp.sh|scripts/watchdog.sh) check_mode "${root}/${path}" 755 || return 1 ;;
      *) check_mode "${root}/${path}" 644 || return 1 ;;
    esac
    digest="$(sha256_file "${root}/${path}")" || return 1
    [[ "${digest}" =~ ^[a-f0-9]{64}$ ]] || return 1
    manifest+="${digest}  ${path}"$'\n'
    case "${path}" in *.sh|*.env) bash -n "${root}/${path}" || return 1 ;; esac
  done <<<"${expected}"
  # Byte comparison enforces order, exact inventory, separators, hashes and the final newline.
  cmp -s <(printf '%s' "${manifest}") "${root}/MANIFEST.sha256" || { fail 'MANIFEST 摘要或清单格式不匹配'; return 1; }
)

validate_archive_headers() {
  local listing root="mihomo-manager-$2"
  listing="$(LC_ALL=C tar --list --verbose --numeric-owner --gzip --file "$1")" || return 1
  [ -n "${listing}" ] || return 1
  # GNU tar prints fixed fields for our deliberately restricted ASCII inventory.
  # Validate every member before extraction, including type, mode, duplicate names and root boundary.
  LC_ALL=C awk -v root="${root}" '
    NF != 6 { bad=1; next }
    {
      mode=$1; name=$6
      if (seen[name]++) bad=1
      if (name == root "/" || name == root "/lib/" || name == root "/metadata/" || name == root "/scripts/") {
        if (mode != "drwxr-xr-x") bad=1
        next
      }
      if (index(name,root "/") != 1) { bad=1; next }
      path=substr(name,length(root)+2)
      if (path == "mm.sh" || path == "mtp.sh" || path == "scripts/watchdog.sh") {
        if (mode != "-rwxr-xr-x") bad=1
      } else if (path == "README.md" || path == "VERSION" || path == "MANIFEST.sha256" || path == "metadata/upstream.env" || path ~ /^lib\/[a-z][a-z0-9-]*\.sh$/) {
        if (mode != "-rw-r--r--") bad=1
      } else bad=1
    }
    END { exit bad }
  ' <<<"${listing}" || { fail '归档路径、文件类型、权限或重复项无效'; return 1; }
}

prepare_candidate() {
  local bundle="$1" destination="$2" actual
  require_tools || return 1
  [ -f "${bundle}" ] || { fail 'bundle 不存在'; return 1; }
  actual="$(sha256_file "${bundle}")" || return 1
  if ! [[ "${PACKAGE_SHA256}" =~ ^[a-f0-9]{64}$ ]] || [ "${actual}" != "${PACKAGE_SHA256}" ]; then fail "SHA256 不匹配：${actual}"; return 1; fi
  gzip -t "${bundle}" || { fail 'gzip 校验失败'; return 1; }
  validate_archive_headers "${bundle}" "${PROJECT_VERSION}" || return 1
  tar --extract --gzip --file "${bundle}" --directory "${destination}" --no-same-owner --same-permissions || return 1
  validate_candidate "${destination}/mihomo-manager-${PROJECT_VERSION}" "${PROJECT_VERSION}"
}

verify_bundle() (
  local temporary
  temporary="$(mktemp -d)" || return 1
  trap 'rm -rf -- "${temporary}"' EXIT
  prepare_candidate "$1" "${temporary}"
)

download() {
  if has_cmd curl; then
    curl -fsSL --proto '=https' --proto-redir '=https' --retry 2 --connect-timeout 10 --max-time 180 "$1" -o "$2"
  elif has_cmd wget; then
    wget -q --timeout=180 -O "$2" "$1"
  else
    fail '需要安装 curl 或 wget'
  fi
}

install_bundle() (
  local bundle="$1" temporary candidate
  temporary="$(mktemp -d)" || return 1
  trap 'rm -rf -- "${temporary}"' EXIT
  prepare_candidate "${bundle}" "${temporary}" || return 1
  candidate="${temporary}/mihomo-manager-${PROJECT_VERSION}"
  (
    # Read by the verified candidate sourced below.
    # shellcheck disable=SC2034
    MM_TEST_MODE=1
    # Sourcing is allowed only after the bootstrap pin and the full candidate verification passed.
    # shellcheck disable=SC1091
    . "${candidate}/mm.sh" || exit 1
    unset MM_TEST_MODE
    declare -F install_project_candidate >/dev/null || { fail '候选缺少事务安装入口'; exit 1; }
    install_project_candidate "${candidate}" "${PROJECT_VERSION}"
  )
)

resolve_action() {
  local action="${1:-}" var
  if [ -n "${action}" ]; then printf '%s' "${action}"; return; fi
  for var in vlrt vxpt wspt tupt anypt hypt socks5pt argo; do
    if [ -n "${!var:-}" ]; then printf ins; return; fi
  done
}

main() {
  local temporary action mtp_install_done=0
  case "${1:-}" in
    --verify-bundle)
      [ "$#" -eq 2 ] || { fail '用法：install.sh --verify-bundle BUNDLE'; return 2; }
      verify_bundle "$2" || return 1
      printf 'bundle 校验通过：%s\n' "$2"
      return 0 ;;
    --print-package-sha)
      [ "$#" -eq 1 ] || return 2
      printf '%s\n' "${PACKAGE_SHA256}"
      return 0 ;;
  esac
  require_tools || return 1
  [ "${EUID:-$(id -u)}" -eq 0 ] || { echo '请使用 root 用户运行。' >&2; return 1; }
  temporary="$(mktemp -d)" || return 1
  if ! download "${PACKAGE_URL}" "${temporary}/bundle.tar.gz"; then
    rm -rf -- "${temporary}"
    fail "下载发布包失败：${PACKAGE_URL}"; return 1
  fi
  if ! install_bundle "${temporary}/bundle.tar.gz"; then rm -rf -- "${temporary}"; return 1; fi
  rm -rf -- "${temporary}"
  printf 'Mihomo Manager %s 安装完成：%s / %s\n' "${PROJECT_VERSION}" "${INSTALL_BIN}" "${MTP_BIN}"
  if [ -n "${mtpt:-}" ]; then bash "${MTP_BIN}" || return 1; mtp_install_done=1; fi
  action="$(resolve_action "$@")" || return 1
  [ -z "${action}" ] || exec "${INSTALL_BIN}" "${action}"
  [ "${mtp_install_done}" -eq 1 ] && return 0
  exec "${INSTALL_BIN}"
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then main "$@"; fi
